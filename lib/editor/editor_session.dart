import 'dart:async';
import 'package:flutter/foundation.dart';
import '../domain/formation.dart';
import '../storage/formation_repository.dart';

/// Document edits are immutable commands. A gesture commits one before/after pair.
class EditCommand {
  final Formation before, after;
  final String label;
  final String? beforeName, afterName;
  EditCommand(this.before, this.after, this.label,
      {this.beforeName, this.afterName});
}

class _SessionSnapshot {
  final int revision;
  final Formation document;
  final String name;
  _SessionSnapshot(this.revision, this.document, this.name);
}

class EditorSession extends ChangeNotifier {
  final FormationRepository repository;
  final bool persistDraft;
  Formation document;
  String name, id;
  String? sourceArchiveId, savedFingerprint;
  // File association is local to an explicitly opened/saved editing session.
  String? filePath, fileFormat, lastFileBackup;
  bool readOnly, deleted = false;
  int revision;
  DateTime createdAt;
  String saveState = '尚无修改';
  String? error;
  Future<String> Function(Formation)? thumbnailGenerator;
  String? thumbnailError;
  final List<EditCommand> _undo = [], _redo = [];
  Timer? _timer;
  Future<void> _tail = Future.value();
  int _savedRevision;
  bool _archiveExists;
  bool _deferInitialSave;
  String? _persistedName;
  String? _legacyDraftId, _legacyCleanupId;
  final List<_SessionSnapshot> _pending = [];
  bool _disposed = false;
  // Retained for compatibility; open tabs now retain their entire command history.
  static const historyBytes = 16 * 1024 * 1024;
  int _newCommandSerial = 0;
  int get undoDepth => _undo.length;
  int get redoDepth => _redo.length;
  int get newCommandSerial => _newCommandSerial;
  EditorSession(this.repository,
      {this.persistDraft = true,
      bool? deferInitialSave,
      Formation? document,
      String? id,
      this.name = '新建阵型',
      this.sourceArchiveId,
      this.readOnly = false,
      this.revision = 0,
      DateTime? createdAt,
      this.savedFingerprint})
      : document = document ?? Formation(),
        id = id ?? newId(),
        createdAt = createdAt ?? DateTime.now(),
        _deferInitialSave = deferInitialSave ??
            (sourceArchiveId == null &&
                revision == 0 &&
                name == '新建阵型' &&
                (document == null ||
                    document.fingerprint == Formation().fingerprint)),
        _savedRevision = revision,
        _archiveExists = sourceArchiveId != null,
        _persistedName = sourceArchiveId != null ? name : null {
    if (persistDraft && !readOnly && !_deferInitialSave) {
      if (sourceArchiveId == null ||
          savedFingerprint != this.document.fingerprint) {
        _savedRevision = -1;
        saveState = '保存中';
        unawaited(flush());
      } else {
        saveState = '已保存';
      }
    }
  }
  factory EditorSession.fromDraft(FormationRepository repo, DraftRecord d) {
    // Legacy drafts became independent archives during v4 migration. Resolve
    // that mapping before the queued initial snapshot touches persistence.
    return EditorSession(repo,
        document: Formation.fromJson(d.document),
        id: d.id,
        name: d.name,
        revision: d.revision,
        createdAt: d.createdAt,
        deferInitialSave: false)
      .._legacyDraftId = d.id
      .._legacyCleanupId = d.id;
  }

  /// A pristine landing page is temporary. Existing archives, including empty
  /// ones intentionally saved by the user, are always resumed as saved work.
  static Future<EditorSession> resume(FormationRepository repository) async {
    var archive = await repository.lastOpenedArchive();
    if (archive == null) {
      final archives = await repository.listArchives();
      // Older versions saved every untouched landing page. Prefer actual work
      // when bootstrapping the new resume pointer, without deleting old records.
      for (final candidate in archives) {
        final autogenerated =
            RegExp(r'^新建阵型(?:（\d+）| \(\d+\))?$').hasMatch(candidate.name);
        final pristine = Formation.fromJson(candidate.document).fingerprint ==
            Formation().fingerprint;
        if (!autogenerated || !pristine) {
          archive = candidate;
          break;
        }
      }
      archive ??= archives.isEmpty ? null : archives.first;
    }
    if (archive == null) return EditorSession(repository);
    final document = Formation.fromJson(archive.document);
    return EditorSession(repository,
        id: archive.id,
        document: document,
        name: archive.name,
        sourceArchiveId: archive.id,
        savedFingerprint: document.fingerprint);
  }

  bool get canUndo => !readOnly && _undo.isNotEmpty;
  bool get canRedo => !readOnly && _redo.isNotEmpty;
  bool get matchesArchive =>
      sourceArchiveId != null &&
      savedFingerprint == document.fingerprint &&
      _persistedName == name;
  void _notify() {
    if (!_disposed) notifyListeners();
  }

  bool execute(String label, Formation next, {String? name}) {
    final nextName =
        name == null || name.trim().isEmpty ? this.name : name.trim();
    if (readOnly ||
        deleted ||
        (document.fingerprint == next.fingerprint && this.name == nextName)) {
      return false;
    }
    Formation.fromJson(
        next.toJson()); // Reject invalid commands before changing history.
    _undo.add(EditCommand(document, next, label,
        beforeName: this.name, afterName: nextName));
    _redo.clear();
    _newCommandSerial++;
    document = next;
    this.name = nextName;
    _changed();
    return true;
  }

  void undo() {
    if (!canUndo) return;
    final c = _undo.removeLast();
    _redo.add(c);
    document = c.before;
    name = c.beforeName ?? name;
    _changed();
  }

  void redo() {
    if (!canRedo) return;
    final c = _redo.removeLast();
    _undo.add(c);
    document = c.after;
    name = c.afterName ?? name;
    _changed();
  }

  void rename(String next) {
    if (next.trim().isNotEmpty) execute('重命名', document, name: next);
  }

  void _changed() {
    _deferInitialSave = false;
    revision++;
    error = null;
    saveState = '保存中';
    // Every immutable command snapshot is queued, including rapid edits. The
    // database retains each previous head rather than coalescing a debounce.
    if (persistDraft) unawaited(flush());
    _notify();
  }

  Future<void> flush({bool forceSave = false}) {
    _timer?.cancel();
    if (!persistDraft || readOnly || deleted) return _tail;
    if (_deferInitialSave) {
      if (!forceSave) return _tail;
      _deferInitialSave = false;
      _savedRevision = -1;
      saveState = '保存中';
    }
    if (revision > _savedRevision &&
        !_pending.any((s) => s.revision == revision)) {
      _pending.add(_SessionSnapshot(revision, document, name));
    }
    _tail = _tail.then((_) async {
      while (_pending.isNotEmpty && !deleted) {
        final snapshot = _pending.first;
        try {
          if (_legacyDraftId != null) {
            final mapped =
                await repository.archiveForLegacyDraft(_legacyDraftId!);
            _legacyDraftId = null;
            if (mapped != null) {
              final archive = (await repository.listArchives())
                  .firstWhere((a) => a.id == mapped);
              sourceArchiveId = mapped;
              _archiveExists = true;
              savedFingerprint = snapshot.document.fingerprint;
              _persistedName = archive.name;
              if (name == snapshot.name) name = archive.name;
              _pending[0] = _SessionSnapshot(
                  snapshot.revision, snapshot.document, archive.name);
              continue;
            }
          }
          final saved = await repository.saveArchive(
              id: id,
              updateId: _archiveExists ? sourceArchiveId : null,
              name: snapshot.name,
              document: snapshot.document.toJson(),
              // Autosave always persists the current edit. The repository
              // archives the latest database head before replacing it.
              preserveMetadata: true,
              uniqueName: !_archiveExists);
          final oldName = snapshot.name;
          if (!_archiveExists && saved.name != oldName) {
            // Canonicalize a generated first-save name in snapshots already
            // queued before that first insert completed.
            for (var i = 1; i < _pending.length; i++) {
              final queued = _pending[i];
              if (queued.name == oldName) {
                _pending[i] = _SessionSnapshot(
                    queued.revision, queued.document, saved.name);
              }
            }
            if (name == oldName) name = saved.name;
          }
          _archiveExists = true;
          sourceArchiveId = saved.id;
          savedFingerprint = snapshot.document.fingerprint;
          _persistedName = saved.name;
          _savedRevision = snapshot.revision;
          if (_legacyCleanupId != null) {
            await repository.discardSavedDraft(_legacyCleanupId!);
            _legacyCleanupId = null;
          }
          _pending.removeAt(0);
          error = null;
          saveState =
              _pending.isEmpty && revision == _savedRevision ? '已保存' : '保存中';
        } catch (e) {
          error = '$e';
          saveState = '保存失败';
          // Retain failed and following snapshots for an ordered retry.
          _notify();
          return;
        }
        _notify();
      }
    });
    return _tail;
  }

  Future<void> markArchived(String archiveId, String fingerprint,
      {String? name}) async {
    await _tail;
    if (_pending.isNotEmpty) throw StateError('仍有未保存的修改，不能切换存档关联');
    _deferInitialSave = false;
    sourceArchiveId = archiveId;
    savedFingerprint = fingerprint;
    _archiveExists = true;
    if (name != null && name.trim().isNotEmpty) this.name = name.trim();
    _persistedName = this.name;
    _savedRevision = revision;
    error = null;
    saveState = '已保存';
    if (document.fingerprint != fingerprint) {
      _savedRevision = -1;
      await flush();
    }
    _notify();
  }

  /// Adopt an already-persisted change without writing a duplicate version.
  /// Keep the previous document and title available for tab-lifetime undo.
  Future<void> reloadSavedArchive(ArchiveRecord archive,
      {bool forceUndo = false}) async {
    await _tail;
    if (_pending.isNotEmpty) throw StateError('存在未保存的修改，不能替换当前存档');
    if (sourceArchiveId != null && sourceArchiveId != archive.id) {
      throw ArgumentError('只能重新加载当前关联的存档');
    }
    final next = Formation.fromJson(archive.document);
    final changed =
        document.fingerprint != next.fingerprint || name != archive.name;
    if (changed || forceUndo) {
      _undo.add(EditCommand(document, next, '恢复存档',
          beforeName: name, afterName: archive.name));
      _redo.clear();
      _newCommandSerial++;
    }
    _deferInitialSave = false;
    document = next;
    name = archive.name;
    sourceArchiveId = archive.id;
    savedFingerprint = document.fingerprint;
    _persistedName = archive.name;
    _archiveExists = true;
    _legacyDraftId = null;
    _legacyCleanupId = null;
    revision++;
    _savedRevision = revision;
    error = null;
    saveState = '已保存';
    _notify();
  }

  Future<void> deleteDraft() async {
    final previousError = error;
    deleted = true;
    _timer?.cancel();
    await _tail;
    try {
      await repository.deleteDraft(id);
    } catch (e) {
      deleted = false;
      error = previousError;
      saveState = revision == 0
          ? '尚无修改'
          : revision == _savedRevision
              ? '已保存'
              : error == null
                  ? '保存中'
                  : '保存失败';
      if (revision > _savedRevision && error == null) {
        if (persistDraft) {
          _timer = Timer(const Duration(milliseconds: 700), flush);
        }
      }
      _notify();
      rethrow;
    }
  }

  @override
  void dispose() {
    _disposed = true;
    _timer?.cancel();
    super.dispose();
  }
}
